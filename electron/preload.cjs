const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('norae', {
  snapshot: () => ipcRenderer.invoke('room:snapshot'),
  add: (input) => ipcRenderer.invoke('room:add', input),
  demo: () => ipcRenderer.invoke('room:demo'),
  remove: (id) => ipcRenderer.invoke('room:remove', id),
  move: (id, direction) => ipcRenderer.invoke('room:move', id, direction),
  reorder: (id, index) => ipcRenderer.invoke('room:reorder', id, index),
  retry: (id) => ipcRenderer.invoke('room:retry', id),
  retryLyrics: (id) => ipcRenderer.invoke('room:retryLyrics', id),
  selectLyrics: (id, candidateId) => ipcRenderer.invoke('room:lyrics', id, candidateId),
  align: (id) => ipcRenderer.invoke('room:align', id),
  saveTiming: (id, input) => ipcRenderer.invoke('room:timing', id, input),
  replaceLyrics: (id, text) => ipcRenderer.invoke('room:replaceLyrics', id, text),
  exportVideo: (id) => ipcRenderer.invoke('room:export', id),
  cancelExport: (id) => ipcRenderer.invoke('room:cancelExport', id),
  saveProject: (id) => ipcRenderer.invoke('room:saveProject', id),
  loadProject: (id) => ipcRenderer.invoke('room:loadProject', id),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (settings) => ipcRenderer.invoke('settings:save', settings),
  check: () => ipcRenderer.invoke('settings:check'),
  chooseModel: () => ipcRenderer.invoke('settings:model'),
  chooseCredentials: () => ipcRenderer.invoke('settings:credentials'),
  fullscreen: (enabled) => ipcRenderer.invoke('window:fullscreen', enabled),
  onChange: (callback) => { const listener = (_event, tracks) => callback(tracks); ipcRenderer.on('room:changed', listener); return () => ipcRenderer.removeListener('room:changed', listener); },
  onStorageError: (callback) => { const listener = (_event, message) => callback(message); ipcRenderer.on('room:storageError', listener); return () => ipcRenderer.removeListener('room:storageError', listener); },
});
