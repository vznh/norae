import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, rm } from 'node:fs/promises';
import path from 'node:path';
await mkdir('.runtime', { recursive: true });
const userData = await mkdtemp(path.resolve('.runtime/smoke-'));
const app = await electron.launch({ args: ['.'], env: { ...process.env, NORAE_TEST_DATA: userData, NORAE_DEV_URL: process.env.NORAE_DEV_URL || '' } });
const errors = [];
try {
  const page = await app.firstWindow(); page.on('pageerror', error => errors.push(error.message));
  await page.getByRole('heading', { name: 'norae', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => typeof window.norae?.add), 'function');
  assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
  await page.screenshot({ path: '.runtime/room-empty.png' });
  await page.getByRole('textbox', { name: 'YouTube URL', exact: true }).fill('https://example.com/watch?v=abcdefghijk');
  await page.getByRole('button', { name: 'Add to queue', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'single YouTube video link' }).waitFor();
  await page.getByRole('textbox', { name: 'YouTube URL', exact: true }).fill('');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Load demo', exact: true }).click();
  await page.getByRole('heading', { name: 'A little louder', exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('audio').currentTime > .5, { timeout: 10000 });
  assert.equal(await page.evaluate(() => document.querySelector('audio').paused), false);
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('audio').paused);
  await page.getByRole('slider', { name: 'Playback position' }).fill('13');
  await page.waitForFunction(() => document.querySelector('.lyric-line.current')?.textContent.includes('Turn the quiet'));
  await page.screenshot({ path: '.runtime/room-demo.png' });
  await page.getByRole('button', { name: 'Cross-check', exact: false }).click();
  await page.getByText('Demo fixture: original instrumental', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Toggle stage view' }).click();
  await page.locator('.stage-lyrics h1').filter({ hasText: 'Turn the quiet into sound' }).waitFor();
  await page.screenshot({ path: '.runtime/stage-demo.png' });
  await page.keyboard.press('Escape');
  await page.getByRole('heading', { name: 'norae', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByLabel('Song language', { exact: false }).fill('en');
  await page.getByRole('button', { name: 'Save & check tools' }).click();
  await page.getByRole('status').waitFor();
  assert.equal(JSON.parse(await readFile(path.join(userData, 'settings.json'), 'utf8')).language, 'en');
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Options for A little louder', exact: true }).click();
  await page.getByRole('button', { name: 'Remove', exact: true }).click();
  await page.getByText('No songs queued.', { exact: true }).waitFor();
  assert.deepEqual(await page.evaluate(() => window.norae.snapshot()), []);
  assert.deepEqual(errors, []);
  console.log('Desktop smoke passed: secure preload, URL rejection, demo audio, seek, lyrics, cross-check, stage, settings persistence, removal.');
} finally {
  await app.close();
  await rm(userData, { recursive: true, force: true });
}
