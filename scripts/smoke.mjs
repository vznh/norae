import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { run } from '../electron/process.mjs';
await mkdir('.runtime', { recursive: true });
const userData = await mkdtemp(path.resolve('.runtime/smoke-'));
await writeFile(path.join(userData, 'settings.json'), JSON.stringify({ lyricsProvider: 'legacy-provider', lyricsCountry: 'US' }));
const app = await electron.launch({ args: ['.'], env: { ...process.env, NORAE_TEST_DATA: userData, NORAE_DEV_URL: process.env.NORAE_DEV_URL || '' } });
const errors = [];
try {
  const page = await app.firstWindow(); page.on('pageerror', error => errors.push(error.message));
  await page.getByRole('heading', { name: 'norae', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => typeof window.norae?.add), 'function');
  assert.equal((await page.evaluate(() => window.norae.getSettings())).lyricsProvider, 'lrclib');
  assert.deepEqual((await page.evaluate(() => window.norae.check())).map(dep => dep.key).sort(), ['elevenlabs', 'ffmpeg', 'ytDlp']);
  assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
  await page.screenshot({ path: '.runtime/room-empty.png' });
  await page.getByRole('textbox', { name: 'Song URL', exact: true }).fill('https://example.com/watch?v=abcdefghijk');
  await page.getByRole('button', { name: 'Add to queue', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'single YouTube video or SoundCloud track link' }).waitFor();
  await page.getByRole('textbox', { name: 'Song URL', exact: true }).fill('');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByText('Lyrics: LRCLIB — free, no API key.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Load demo', exact: true }).click();
  await page.getByRole('heading', { name: 'A little louder', exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('audio').currentTime > .5, { timeout: 10000 });
  assert.equal(await page.evaluate(() => document.querySelector('audio').paused), false);
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('audio').paused);
  await page.getByRole('slider', { name: 'Playback position' }).fill('13');
  await page.waitForFunction(() => document.querySelector('.lyric-line.current')?.textContent.includes('Turn the quiet'));
  await page.screenshot({ path: '.runtime/room-demo.png' });
  await page.getByRole('button', { name: 'Cross-check', exact: false }).click();
  await page.getByText('Demo fixture: original instrumental', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Edit timing', exact: true }).click();
  await page.getByLabel('Lyric line', { exact: true }).selectOption('2');
  await page.getByRole('button', { name: 'Split syllables', exact: true }).first().click();
  await page.getByLabel('Syllable split', { exact: true }).fill('Tu|rn');
  await page.getByRole('button', { name: 'Apply split', exact: true }).click();
  await page.getByLabel('Start of unit 1', { exact: true }).fill('11.01');
  await page.getByText('Unsaved changes — save timing', { exact: false }).waitFor();
  await page.evaluate(() => { window.confirm = () => false; });
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog', { name: 'Edit timing' }).isVisible(), true);
  await page.getByLabel('I reviewed these timings', { exact: true }).check();
  await page.getByRole('button', { name: 'Save timing', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Timing saved' }).waitFor();
  const edited = await page.evaluate(() => window.norae.snapshot());
  assert.equal(edited[0].result.lines[2].words[0].text, 'Tu');
  assert.equal(edited[0].result.lines[2].words[0].start, 11.01);
  assert.equal(edited[0].reviewed, true);
  await page.getByText('Edit line and verse layout', { exact: true }).click();
  const layout = edited[0].result.lines.map((line, i) => `${i === 0 ? '[Verse 1]\n' : i === 4 ? '\n[Chorus]\n' : ''}${i === 2 ? 'Turn the quiet\ninto sound' : line.text}`).join('\n');
  await page.getByLabel('Line and verse layout', { exact: true }).fill(layout);
  await page.getByRole('button', { name: 'Apply verse layout', exact: true }).click();
  await page.getByRole('button', { name: 'Save timing', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Timing saved' }).waitFor();
  const reflowed = (await page.evaluate(() => window.norae.snapshot()))[0].result.lines;
  assert.equal(reflowed.length, 7); assert.equal(reflowed[2].text, 'Turn the quiet');
  assert.equal(reflowed[2].words[0].start, 11.01); assert.equal(reflowed[0].section, 'Verse 1'); assert.equal(reflowed[5].section, 'Chorus');
  const projectPath = path.resolve('.runtime/demo-timing.norae.json');
  await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filePath] }); }, projectPath);
  await page.getByRole('button', { name: 'Save project file', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Timing project saved' }).waitFor();
  await page.getByRole('button', { name: 'Load project file', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Timing project loaded' }).waitFor();
  assert.equal((await page.evaluate(() => window.norae.snapshot()))[0].result.lines[2].words[0].start, 11.01);
  assert.equal((await page.evaluate(() => window.norae.snapshot()))[0].result.lines[5].section, 'Chorus');
  await page.screenshot({ path: '.runtime/timing-editor.png' });
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Toggle stage view' }).click();
  await page.getByRole('img', { name: 'Four-line karaoke video preview' }).waitFor();
  await page.screenshot({ path: '.runtime/stage-demo.png' });
  await page.keyboard.press('Escape');
  await page.getByRole('heading', { name: 'norae', exact: true }).waitFor();
  const exportPath = path.resolve('.runtime/demo-export.mp4');
  await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); }, exportPath);
  await page.getByRole('button', { name: 'Export MP4', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Saved demo-export.mp4' }).waitFor({ timeout: 120000 });
  const encoded = JSON.parse(await run('ffprobe', ['-v', 'error', '-show_streams', '-show_format', '-of', 'json', exportPath]));
  assert.equal(encoded.streams.find(stream => stream.codec_type === 'video').width, 1920);
  assert.equal(encoded.streams.find(stream => stream.codec_type === 'video').height, 1080);
  assert.equal(encoded.streams.find(stream => stream.codec_type === 'video').codec_name, 'h264');
  assert.ok(encoded.streams.some(stream => stream.codec_type === 'audio'));
  assert.ok(Math.abs(Number(encoded.format.duration) - 30) < .2);
  await run('ffmpeg', ['-nostdin', '-loglevel', 'error', '-y', '-ss', '13', '-i', exportPath, '-frames:v', '1', path.resolve('.runtime/export-frame.png')]);
  await run('ffmpeg', ['-nostdin', '-loglevel', 'error', '-y', '-ss', '1.5', '-i', exportPath, '-frames:v', '1', path.resolve('.runtime/export-lead-in.png')]);
  await run('ffmpeg', ['-nostdin', '-loglevel', 'error', '-y', '-ss', '13.4', '-i', exportPath, '-frames:v', '1', path.resolve('.runtime/export-line-handoff.png')]);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  assert.equal(await page.getByLabel('Song language', { exact: false }).inputValue(), 'en');
  await page.getByRole('button', { name: 'Save & check tools' }).click();
  await page.getByRole('status').waitFor();
  assert.equal(JSON.parse(await readFile(path.join(userData, 'settings.json'), 'utf8')).language, 'en');
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Options for A little louder', exact: true }).click();
  await page.getByRole('button', { name: 'Remove', exact: true }).click();
  await page.getByText('No songs queued.', { exact: true }).waitFor();
  assert.deepEqual(await page.evaluate(() => window.norae.snapshot()), []);
  assert.deepEqual(errors, []);
  console.log('Desktop smoke passed: secure preload, audio, syllable timing, verse reflow/labels, project persistence, reading-line preview, 1080p H.264/AAC MP4, removal.');
} finally {
  await app.close();
  await rm(userData, { recursive: true, force: true });
}
